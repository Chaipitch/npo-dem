import { LightningElement, api, wire } from 'lwc';
import { updateRecord } from 'lightning/uiRecordApi';
import { gql, graphql, refreshGraphQL } from 'lightning/uiGraphQLApi';
import { ShowToastEvent } from 'lightning/platformShowToastEvent';
import RUNNING_USER_ID from '@salesforce/user/Id';

// Placeholder — replace with the stable "How to use Demo Mode" guide/video URL.
const HOWTO_URL = 'https://salesforce.vidyard.com/watch/X3TWi3mZBFer7vG9vaszwr';

export default class SeCoachingCard extends LightningElement {
    // --- Slot properties (set per FlexiPage instance in App Builder) ---
    @api pageTitle;
    @api soundbite;
    @api platformTieIn;
    @api orientation;
    @api persona;
    @api valueStory;
    // JSON string: [{ "name": "...", "value": "..." }, ...]
    @api componentsJson;
    // JSON string of custom (non-standard) metadata on this page, grouped by type:
    // { "Components": ["..."], "Quick Actions": ["..."], "Flows": ["..."] }
    @api customItemsJson;

    // "ido" (full value/story card, default) or "template" (lightweight
    // "from SDO Template" reference card with contributing brix).
    @api cardVariant = 'ido';
    // Template variant only — JSON array of contributing brix names: ["...", ...]
    @api brixJson;

    // Seconds to wait after the save commits before reloading, giving the
    // FlexiPage component-visibility context time to pick up the new value.
    // Configurable in App Builder; defaults to 5 seconds.
    @api refreshDelaySeconds = 5;

    get isTemplateCard() {
        return this.cardVariant === 'template';
    }

    get isIdoCard() {
        return !this.isTemplateCard;
    }

    get bannerTitle() {
        const prefix = this.isTemplateCard ? '📦 SE Reference' : '🎤 SE Demo Coaching';
        return `${prefix} — ${this.pageTitle || ''}`;
    }

    get bannerNote() {
        return this.isTemplateCard
            ? 'Internal enablement. Reference info for a base SDO-template page. Auto-generated each release.'
            : 'Internal enablement. Text generated by AI based on the default IDO. Any customizations will not be included.';
    }

    get brixList() {
        if (!this.brixJson) {
            return [];
        }
        try {
            const parsed = JSON.parse(this.brixJson);
            return Array.isArray(parsed)
                ? parsed.map((name, i) => ({ key: `b${i}`, name }))
                : [];
        } catch (e) {
            return [];
        }
    }

    get hasBrix() {
        return this.brixList.length > 0;
    }

    howtoUrl = HOWTO_URL;
    runningUserId = RUNNING_USER_ID;
    isSaving = false;
    graphQLResult;
    error;

    get refreshDelayMs() {
        const seconds = Number(this.refreshDelaySeconds);
        return Number.isFinite(seconds) && seconds >= 0 ? seconds * 1000 : 5000;
    }

    get components() {
        if (!this.componentsJson) {
            return [];
        }
        try {
            const parsed = JSON.parse(this.componentsJson);
            return Array.isArray(parsed)
                ? parsed.map((c, i) => ({ key: `${i}`, name: c.name, value: c.value }))
                : [];
        } catch (e) {
            return [];
        }
    }

    // Fixed display order for the groups that exist.
    get customGroups() {
        if (!this.customItemsJson) {
            return [];
        }
        let parsed;
        try {
            parsed = JSON.parse(this.customItemsJson);
        } catch (e) {
            return [];
        }
        if (!parsed || typeof parsed !== 'object') {
            return [];
        }
        const order = ['Components', 'Quick Actions', 'Flows'];
        const groups = [];
        order.forEach((label, gi) => {
            const items = parsed[label];
            if (Array.isArray(items) && items.length) {
                groups.push({
                    key: `g${gi}`,
                    label,
                    items: items.map((name, i) => ({ key: `g${gi}i${i}`, name }))
                });
            }
        });
        return groups;
    }

    get hasCustomItems() {
        return this.customGroups.length > 0;
    }

    @wire(graphql, {
        query: gql`
            query ActiveUsersDemoMode {
                uiapi {
                    query {
                        User(
                            where: {
                                and: [
                                    { IsActive: { eq: true } }
                                    { UserType: { eq: "Standard" } }
                                ]
                            }
                            first: 200
                        ) {
                            edges {
                                node {
                                    Id
                                    Demo_Mode__c {
                                        value
                                    }
                                    Profile {
                                        Name {
                                            value
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        `
    })
    handleGraphQL(result) {
        this.graphQLResult = result;
        this.error = result.error;
    }

    get activeUsers() {
        const edges = this.graphQLResult?.data?.uiapi?.query?.User?.edges ?? [];
        return edges
            .map((edge) => edge.node)
            .filter((u) => {
                const profileName = u.Profile?.Name?.value ?? '';
                return !profileName.includes('Integration');
            });
    }

    async handleEnableDemoMode(event) {
        if (event) {
            event.preventDefault();
        }
        if (this.isSaving) {
            return;
        }
        this.isSaving = true;

        // This link only ever enables Demo Mode (the card is hidden once it is on).
        const newValue = true;
        const usersToUpdate = this.activeUsers.filter(
            (u) => u.Demo_Mode__c?.value !== newValue
        );

        if (usersToUpdate.length === 0) {
            this.isSaving = false;
            this.dispatchEvent(
                new ShowToastEvent({
                    title: 'No changes needed',
                    message: 'All active users already have Demo Mode ON.',
                    variant: 'info'
                })
            );
            return;
        }

        const results = await Promise.allSettled(
            usersToUpdate.map((u) =>
                updateRecord({ fields: { Id: u.Id, Demo_Mode__c: newValue } })
            )
        );

        const failures = [];
        results.forEach((r, idx) => {
            if (r.status === 'rejected') {
                const userId = usersToUpdate[idx].Id;
                const err = r.reason;
                const message =
                    err?.body?.message ||
                    err?.body?.output?.errors?.[0]?.message ||
                    err?.message ||
                    'Unknown error';
                // eslint-disable-next-line no-console
                console.error(`[seCoachingCard] Failed for User ${userId}:`, message, err);
                failures.push({ userId, message });
            }
        });

        const successCount = usersToUpdate.length - failures.length;

        if (failures.length === 0) {
            this.dispatchEvent(
                new ShowToastEvent({
                    title: 'Demo Mode Updated',
                    message: `Demo Mode is now ON for ${successCount} user${successCount === 1 ? '' : 's'}.`,
                    variant: 'success'
                })
            );
            // The updateRecord calls above have already committed server-side, but
            // the running-user context that FlexiPage component-visibility rules
            // evaluate against refreshes on its own cadence and lags behind the
            // record write by a few seconds. That path is not observable from this
            // component (polling our own GraphQL query returns the LDS-cached value,
            // which flips optimistically on save), so we wait a fixed settle window
            // before reloading to give the visibility context time to catch up.
            await this.delay(this.refreshDelayMs);
            // eslint-disable-next-line no-restricted-globals
            window.location.reload();
        } else {
            await refreshGraphQL(this.graphQLResult);
            // eslint-disable-next-line no-console
            console.table(failures);
            const first = failures[0];
            this.dispatchEvent(
                new ShowToastEvent({
                    title: `Demo Mode: ${successCount} succeeded, ${failures.length} failed`,
                    message: `First failure — User ${first.userId}: ${first.message}. See browser console for full list.`,
                    variant: 'warning',
                    mode: 'sticky'
                })
            );
            this.isSaving = false;
        }
    }

    delay(ms) {
        // eslint-disable-next-line @lwc/lwc/no-async-operation
        return new Promise((resolve) => setTimeout(resolve, ms));
    }
}